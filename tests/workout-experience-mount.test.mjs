test('a timed set keeps its start through view changes and cannot be replaced from another log row', async t => {
  t.after(unmount); localStorage.clear();
  t.mock.timers.enable({ apis: ['Date', 'setInterval'], now: 1700000000000 });
  await mount(); await click('Focus');
  await act(async () => rootElement.querySelector('summary').click());
  await click('Timed sets'); await click('Start set 1');
  const running = draft(); assert.equal(running.activeSetKey, '0-0');
  await act(async () => t.mock.timers.tick(5000));
  await click('Change view'); await click('Workout log');
  assert.equal(draft().setStartedAt, running.setStartedAt);
  const other = document.getElementById('bs-log-move-1').closest('section');
  await act(async () => other.querySelector('button[aria-label="Start set 1"]').click());
  assert.equal(draft().activeSetKey, '0-0'); assert.equal(draft().setStartedAt, running.setStartedAt);
  await click('Change view'); await click('Guided coach');
  assert.equal(draft().setStartedAt, running.setStartedAt);
  await click('Log set 1 · 8 reps');
  assert.equal(draft().setLogs[0].setDurationSeconds, 5);
});

