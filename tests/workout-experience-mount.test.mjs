test('mounted views share typed values, logs, trainer rest and a durable client preference',async t=>{
  t.after(unmount);localStorage.clear();await mount();
  assert.match(rootElement.textContent,/Choose your workout view/);
  await click('Focus');assert.equal(localStorage.getItem('shapeClientWorkoutView:client-a'),'focus');
  await type(input('Set 1 Load'),'62.5 kg');
  await type(input('Set 1 RPE'),'7');
  await click('Log set 1 · 8 reps');
  const first=draft();assert.equal(first.setLogs[0].actualLoad,62.5);assert.equal(Number(first.setLogs[0].rpe),7);assert.equal(first.restTotal,90);
  await click('Change view');await click('Workout log');
  assert.equal(draft().restEnd,first.restEnd,'switch must retain the absolute rest deadline');
  const rowSection=document.getElementById('bs-log-move-1').closest('section');
  assert.equal(input('Set 1 Reps',rowSection).value,'10 each');
  await type(input('Set 1 Load',rowSection),'27.5 kg');
  await act(async()=>rowSection.querySelector('button[aria-label="Mark set 1 done"]').click());
  assert.equal(draft().setLogs.find(s=>s.moveIndex===1).actualLoad,27.5,'logging another exercise uses that row');
  assert.equal(draft().setLogs.find(s=>s.moveIndex===1).enteredReps,'10 each');
  await click('Change view');await click('Guided coach');
  const kept=draft();assert.equal(kept.setLogs.length,2);assert.equal(kept.view,'guided');
  await unmount();await mount({draft:kept});
  assert.doesNotMatch(rootElement.textContent,/Choose your workout view/);
  assert.match(rootElement.textContent,/Guided coach/);
  assert.equal(draft().setLogs.length,2);
  await click('Skip rest →');
  assert.ok(!!button('Ready for this set'));
  await click('Ready for this set');
  assert.match(rootElement.textContent,/02 · Perform & log/);
  assert.equal(draft().setLogs.length,2,'prepare does not log or invent timing');
});

